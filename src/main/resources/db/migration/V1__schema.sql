-- Schema per docs/architecture.md "Data model". Runs on H2 (PostgreSQL mode) and PostgreSQL.
-- Never edit after merge; later changes go in new versions.

create table recipient (
    id    varchar(64)  not null,
    email varchar(254),
    phone varchar(20),
    constraint pk_recipient primary key (id)
);

create table channel_preference (
    recipient_id varchar(64) not null,
    channel      varchar(16) not null,
    enabled      boolean     not null,
    constraint pk_channel_preference primary key (recipient_id, channel),
    constraint fk_channel_preference_recipient foreign key (recipient_id) references recipient (id)
);

create table idempotency_record (
    id              bigint generated by default as identity,
    source_system   varchar(64)              not null,
    idempotency_key varchar(128)             not null,
    request_hash    char(64)                 not null,
    submission_id   uuid                     not null,
    created_at      timestamp with time zone not null,
    expires_at      timestamp with time zone not null,
    constraint pk_idempotency_record primary key (id),
    constraint uk_idempotency_record_source_key unique (source_system, idempotency_key)
);

create table notification (
    id                 uuid                     not null,
    submission_id      uuid                     not null,
    source_system      varchar(64)              not null,
    event_id           varchar(128)             not null,
    type               varchar(64)              not null,
    severity           varchar(16)              not null,
    priority           varchar(16)              not null,
    recipient_id       varchar(64)              not null,
    requested_channels varchar(64),
    subject            varchar(200)             not null,
    body               varchar(5000)            not null,
    scheduled_at       timestamp with time zone,
    expires_at         timestamp with time zone,
    created_at         timestamp with time zone not null,
    constraint pk_notification primary key (id),
    constraint fk_notification_recipient foreign key (recipient_id) references recipient (id)
);

create index ix_notification_submission_id on notification (submission_id);

create table delivery (
    id                  uuid                     not null,
    notification_id     uuid                     not null,
    channel             varchar(16)              not null,
    provider            varchar(32)              not null,
    status              varchar(20)              not null,
    priority            smallint                 not null,
    routing_reason      varchar(32)              not null,
    attempt_count       integer                  not null,
    next_attempt_at     timestamp with time zone,
    claimed_at          timestamp with time zone,
    provider_message_id varchar(128),
    failure_reason      varchar(32),
    sent_at             timestamp with time zone,
    finalized_at        timestamp with time zone,
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null,
    version             bigint                   not null,
    constraint pk_delivery primary key (id),
    constraint fk_delivery_notification foreign key (notification_id) references notification (id),
    constraint uk_delivery_notification_channel unique (notification_id, channel),
    constraint uk_delivery_provider_message unique (provider, provider_message_id)
);

create index ix_delivery_poll on delivery (status, priority, next_attempt_at);

create sequence audit_event_seq increment by 50;

create table audit_event (
    id              bigint                   not null,
    source_system   varchar(64)              not null,
    notification_id uuid,
    delivery_id     uuid,
    type            varchar(32)              not null,
    channel         varchar(16),
    detail          varchar(256)             null,
    occurred_at     timestamp with time zone not null,
    constraint pk_audit_event primary key (id)
);

create index ix_audit_event_notification_id on audit_event (notification_id);
